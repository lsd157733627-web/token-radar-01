// Token Radar model (radar-2): category-calibrated implied values and farm plans for pre-token protocols.
// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other pre-token protocol the snapshot holds that is rankable: 40 watchlist rows plus the 186
// pre-token protocols below the floor, 226 rows in all. A protocol is pre-token when its index entry
// records no token (no market cap, no CoinGecko id, no symbol); live-token protocols are kept apart
// and shown with the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The starter's flat 0.25x TVL for
// every protocol is the thing this model fixes: the market does not price a DEX's TVL like a
// lender's, and the snapshot itself proves it, so each category's multiple is calibrated from the
// live protocols in that category:
//
//   multiple(cat) = clamp( (n * median(mcap/TVL of live protocols in cat) + 8 * global_median)
//                          / (n + 8), 0.05, 0.80 )
//
// The 8 pseudo-observations shrink thin categories toward the global median, so a category with one
// live protocol (Risk Curators, median 2.97x) or none at all (CeDeFi, Insurance) still gets a sane
// multiple instead of an outlier or a guess. No protocol name is ever special-cased: the same
// function scores every row, and the dashboard prints the whole calibration table.
//
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(chains, 5)
//   implied    = max(1, round(tvl_usd x multiple(cat) x growthMult x maturity x breadth))
//
// Age is the time since DefiLlama first listed the protocol, the best record of how long it has run
// with no token. Breadth counts the chains the protocol's TVL sits on: a protocol live on five
// chains has proved more than one live on a single chain. Every constant is stated in the dashboard
// and the model's calibration table is printed beside the board, so a reader can check the arithmetic
// behind any row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

